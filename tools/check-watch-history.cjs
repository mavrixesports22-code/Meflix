const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const History = require(fs.existsSync(path.join(__dirname, '../js/watch-history.js')) ? '../js/watch-history.js' : '../netflix/js/watch-history.js');
const data = new Map();
const storage = { getItem: key => data.get(key) || null, setItem: (key, value) => data.set(key, value), removeItem: key => data.delete(key) };
const input = (id = '1', playId = 'episode1', position = 42) => ({ item: { id: 'nm-' + id, netmirrorId: id, title: 'Example ' + id, type: 'series', poster: '/poster', backdrop: 'https://example.com/art', token: 'must-not-save', url: 'must-not-save' }, playId, seasonId: 'season2', episode: 'Episode 1', position, duration: 1000, url: 'must-not-save' });
const history = new History(storage);
assert.equal(history.entries.length, 0);
history.record(input());
assert.equal(history.continuing()[0].position, 42);
assert.equal(history.entries[0].seasonId, 'season2');
assert.ok(!storage.getItem(history.key).includes('must-not-save'), 'Only allowlisted title metadata and positions may persist');
history.record(input('1', 'episode2', 90));
assert.equal(history.recent().length, 1, 'Recently Played lists each title once');
assert.equal(history.entries.length, 2, 'Full history retains exact episodes');
assert.equal(history.forTitle('1').playId, 'episode2');
history.record(input('1', 'episode2', 970));
assert.equal(history.continuing().length, 0, 'A finished latest episode must not resurrect an older unfinished episode');
const restored = new History(storage);
assert.equal(restored.entries[0].completed, true);
assert.equal(restored.entries[0].playId, 'episode2');
storage.setItem('netmirror_progress_episode2', '970');
restored.remove('1:episode2');
assert.equal(storage.getItem('netmirror_progress_episode2'), null);
restored.clear(); assert.equal(new History(storage).entries.length, 0);
for (let i = 0; i < 120; i++) history.record(input(String(i), String(i), 10));
assert.equal(history.entries.length, 100, 'History storage stays bounded');
history.record({ ...input(), position: Infinity }); assert.equal(history.entries.length, 100);
assert.equal(history.normalize({ ...input(), item: { ...input().item, poster: 'javascript:alert(1)' } }).item.poster, '');
storage.setItem(history.key, '{broken'); assert.equal(new History(storage).entries.length, 0);
const denied = new History({ getItem() { throw Error('denied'); }, setItem() { throw Error('denied'); } });
denied.record(input()); assert.equal(denied.continuing().length, 1, 'Blocked storage still permits in-memory history');
console.log('PASS: persistent exact-episode history, latest-title deduplication, completed exclusion, removal/clear, bounded storage, invalid data and private-field exclusion');
